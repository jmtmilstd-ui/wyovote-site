#!/usr/bin/env python3
"""Officials Profile chrome for candidate Level-3 pages (and sitting pointers).

Used by the candidate and local builders so a later rebuild, or the nightly
schedule refresh of county pages, keeps this format.

    python3 -B tools/render_candidate_profile.py --all
    python3 -B tools/render_candidate_profile.py PAGE.html [PAGE.html ...]
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
import unicodedata
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OFFICIALS = ROOT / "officials"
CANDIDATES = ROOT / "candidates"
REDIRECTS = ROOT / "_redirects"
REDIR_BEGIN = "# BEGIN sitting-legislator L3 (generated by tools/render_candidate_profile.py)"
REDIR_END = "# END sitting-legislator L3"

BLANK_HEADINGS = {"none", "n/a", "na", "not found", "none found", "none documented"}


def esc(text: str) -> str:
    return html.escape(text or "", quote=True)


def one(pattern: str, text: str, flags: int = 0) -> str | None:
    m = re.search(pattern, text, flags)
    return m.group(1) if m else None


def norm_name(value: str) -> str:
    text = html.unescape(value or "")
    text = unicodedata.normalize("NFD", text)
    text = "".join(ch for ch in text if unicodedata.category(ch) != "Mn")
    text = re.sub(r"[^a-z0-9]+", " ", text.casefold())
    return " ".join(text.split())


def first_last(normalized: str) -> tuple[str, str] | None:
    parts = normalized.split()
    if len(parts) < 2:
        return None
    return parts[0], parts[-1]


def rel_to_root(page: Path) -> str:
    depth = len(page.resolve().relative_to(ROOT).parts) - 1
    return "../" * depth


def cycle_of(page: Path) -> str | None:
    parts = page.resolve().relative_to(ROOT).parts
    if len(parts) >= 3 and parts[0] == "candidates":
        return parts[1]
    return None


@lru_cache(maxsize=1)
def official_pages() -> list[dict]:
    """Every Officials Profile (current root and year archives) with its h1."""
    rows: list[dict] = []
    current = {p.stem.replace("-deep", "") for p in OFFICIALS.glob("*-deep.html")}
    for path in list(OFFICIALS.glob("*-deep.html")) + list(OFFICIALS.glob("20[0-9][0-9]/*-deep.html")):
        text = path.read_text(encoding="utf-8")
        raw = one(r"<h1[^>]*>(.*?)</h1>", text, re.S)
        if not raw:
            continue
        name = html.unescape(re.sub(r"<[^>]+>", "", raw)).strip()
        rel = path.relative_to(OFFICIALS)
        if rel.parent.name.startswith("20"):
            year = int(rel.parent.name)
            sitting = False
        else:
            year = 2026
            sitting = True
        slug = path.stem.replace("-deep", "")
        rows.append(
            {
                "slug": slug,
                "year": year,
                "name": name,
                "norm": norm_name(name),
                "path": path,
                "sitting": sitting and slug in current,
                "current": path.parent == OFFICIALS,
            }
        )
    return rows


@lru_cache(maxsize=1)
def official_indexes() -> tuple[dict[str, list[dict]], dict[tuple[str, str], set[str]]]:
    by_norm: dict[str, list[dict]] = {}
    fl_to_slugs: dict[tuple[str, str], set[str]] = {}
    for row in official_pages():
        by_norm.setdefault(row["norm"], []).append(row)
        fl = first_last(row["norm"])
        if fl:
            fl_to_slugs.setdefault(fl, set()).add(row["slug"])
    return by_norm, fl_to_slugs


def official_matches(names: list[str]) -> list[dict]:
    by_norm, fl_slugs = official_indexes()
    found: list[dict] = []
    seen: set[str] = set()
    slugs: set[str] = set()
    fls: set[tuple[str, str]] = set()
    for name in names:
        if not name:
            continue
        key = norm_name(name)
        if not key:
            continue
        if key in by_norm:
            slugs.update(row["slug"] for row in by_norm[key])
        fl = first_last(key)
        if fl and len(fl_slugs.get(fl, set())) == 1:
            slugs.add(next(iter(fl_slugs[fl])))
            fls.add(fl)
        elif fl:
            fls.add(fl)
    for row in official_pages():
        if row["slug"] not in slugs:
            continue
        # Keep slug-reuse (Mark vs Clifford Jennings) from crossing.
        row_fl = first_last(row["norm"])
        if fls and row_fl not in fls and row["norm"] not in {norm_name(n) for n in names if n}:
            continue
        ident = f"{row['slug']}:{row['year']}:{row['norm']}"
        if ident not in seen:
            seen.add(ident)
            found.append(row)
    return found


def sitting_slug(names: list[str]) -> str | None:
    current = [row for row in official_matches(names) if row["current"] and row["sitting"]]
    if not current:
        return None
    current.sort(key=lambda r: r["year"], reverse=True)
    return current[0]["slug"]


def last_archive_profile(names: list[str]) -> dict | None:
    """Latest year-folder Officials Profile whose name matches, for rank/band."""
    archive = [row for row in official_matches(names) if not row["current"]]
    if not archive:
        return None
    archive.sort(key=lambda r: r["year"], reverse=True)
    return archive[0]


def rank_band_html(profile: dict) -> str:
    text = profile["path"].read_text(encoding="utf-8")
    parts = []
    for sid in ("h-rank", "h-band"):
        m = re.search(
            rf'<section class="pf-card" aria-labelledby="{sid}">.*?</section>',
            text,
            re.S,
        )
        if m:
            parts.append(m.group(0).strip())
    return "\n".join(parts)


GENERAL_SCRIPT = r"""<script>
      (function () {
        var general = new URLSearchParams(location.search).get("e") === "general";
        document.documentElement.classList.toggle("cand-general", general);
        if (general) {
          var nodes = document.querySelectorAll("[data-election-label]");
          for (var i = 0; i < nodes.length; i++) {
            var next = nodes[i].getAttribute("data-election-label-general");
            if (next) nodes[i].textContent = next;
          }
          if (document.title.indexOf("Primary") !== -1) {
            document.title = document.title.replace("Primary", "General");
          }
        }
        var link = document.getElementById("cand-back");
        if (!link) return;
        function countyName(slug) {
          return slug.split("-").map(function (word) {
            return word.charAt(0).toUpperCase() + word.slice(1);
          }).join(" ");
        }
        function useCounty(slug) {
          if (!/^[a-z]+(?:-[a-z]+)*$/.test(slug)) return false;
          link.setAttribute("href", "../" + slug + ".html" + (general ? "?e=general" : ""));
          link.textContent = "\u2190 Back to " + countyName(slug) + " County";
          return true;
        }
        var from = new URLSearchParams(location.search).get("from");
        if (from && useCounty(from)) return;
      })();
    </script>"""


