def research_card(heading: str | None, facts: str | None, sources: str | None) -> str:
    has_facts = bool(facts and facts.strip())
    has_sources = bool(sources and sources.strip())
    if not has_facts and not has_sources:
        return ""
    hid = "h-research" if has_facts else "h-sources"
    parts = [f'        <section class="pf-card cand-research" aria-labelledby="{hid}">']
    if has_facts and heading:
        parts.append(f'          <h2 id="h-research">{esc(heading)}</h2>')
        parts.append(f"          {facts.strip()}")
    if has_sources:
        parts.append('          <div class="cand-sources-block">')
        parts.append('            <h2 id="h-sources">Sources</h2>')
        parts.append(f"            {sources.strip()}")
        parts.append("          </div>")
    parts.append("        </section>")
    return "\n".join(parts)


def pointer_page(page: Path, name: str, official: str, description: str, back: str | None) -> str:
    rel = rel_to_root(page)
    target = f"{rel}officials/{official}-deep.html"
    cycle = cycle_of(page) or ""
    year = cycle.split("-")[0] if cycle else ""
    script = GENERAL_SCRIPT if "primary" in cycle else ""
    back_html = back or f'<p class="back-row"><a class="back-btn" href="{rel}candidates.html">← Back to Candidates</a></p>'
    inner = f"""        {back_html}
        <section class="pf-head" aria-labelledby="h-name">
          <h1 id="h-name">{esc(name)}</h1>
          <p class="pf-sub">Profile</p>
        </section>
        <section class="pf-card">
          <p>{esc(name)} is a sitting legislator. This page has moved to the Officials Profile.</p>
          <p class="pf-links"><a class="pf-btn" href="{esc(target)}">Officials Profile →</a></p>
        </section>"""
    html_out = profile_shell(
        name=name,
        title=f"{name} — Profile — WyoVote",
        description=description or f"{name} Officials Profile.",
        rel=rel,
        nav_current="candidates",
        html_class="",
        body_inner=inner,
        script=script,
    )
    # Meta refresh so the file itself sends people to Officials even without Cloudflare.
    html_out = html_out.replace(
        '<meta name="viewport"',
        f'<meta http-equiv="refresh" content="0;url={esc(target)}">\n    <link rel="canonical" href="/officials/{esc(official)}-deep.html">\n    <meta name="viewport"',
        1,
    )
    return html_out


def names_from_page(text: str, name: str) -> list[str]:
    names = [name]
    # "Jeanette Ward (Republican..." blurb often starts with the same name
    return names


def rewrite_page(page: Path) -> str:
    """Rewrite one candidate L3 page. Returns 'pointer', 'profile', or 'skip'."""
    raw = page.read_text(encoding="utf-8")
    name = one(r"<h1[^>]*>([^<]+)</h1>", raw)
    if not name:
        raise SystemExit(f"no h1 in {page}")
    desc = one(r'<meta name="description" content="([^"]*)"', raw) or ""
    back = one(r'(<p class="back-row">.*?</p>)', raw, re.S)
    blurb = one(r'(<p class="cand-blurb">.*?</p>)', raw, re.S)
    meta = one(r'<p class="cand-meta">([^<]*)</p>', raw) or ""
    results = re.findall(
        r'(<p class="cand-res(?: cand-general-line)?">.*?</p>)', raw, re.S
    )
    research_sec = one(
        r'(<section class="(?:pf-card )?cand-research"[^>]*>.*?</section>)', raw, re.S
    )
    facts = None
    sources = None
    heading = None
    if research_sec:
        heading = one(r'<h2 id="h-research">([^<]+)</h2>', research_sec)
        facts = one(r'(<table class="cand-facts">.*?</table>)', research_sec, re.S)
        sources = one(r'(<ul class="cand-sources">.*?</ul>)', research_sec, re.S)

    names = names_from_page(raw, name)
    sitting = sitting_slug(names)
    # An existing Officials-profile link is a strong sitting signal, but only
    # if the target is a current Officials Profile for this person.
    if not sitting:
        linked = one(r'officials/([a-z0-9-]+)-deep\.html', raw)
        if linked and (OFFICIALS / f"{linked}-deep.html").is_file():
            # Confirm the linked profile name matches, to avoid a stale slug.
            linked_rows = [r for r in official_pages() if r["slug"] == linked and r["current"]]
            if linked_rows and (not linked_rows[0]["norm"] or linked_rows[0]["norm"] == norm_name(name) or first_last(linked_rows[0]["norm"]) == first_last(norm_name(name))):
                sitting = linked

    cycle = cycle_of(page) or ""
    year = cycle.split("-")[0] if cycle else ""
    kind = "Local" if "local" in cycle else "Primary" if "primary" in cycle else ""
    rel = rel_to_root(page)

    if sitting:
        page.write_text(pointer_page(page, name, sitting, desc, back), encoding="utf-8")
        return "pointer", sitting

    meta_txt = re.sub(r"\s+", " ", html.unescape(meta)).strip(" ·")
    sub_bits = ["Profile"]
    if meta_txt:
        sub_bits.append(meta_txt)
    if year and kind == "Primary":
        sub_bits.append(
            f'<span data-election-label data-election-label-general="{esc(year)} General">{esc(year)} Primary</span>'
        )
    elif year and kind:
        sub_bits.append(esc(f"{year} {kind}"))
    elif year:
        sub_bits.append(esc(year))
    sub = " · ".join(sub_bits)

    extra = []
    if blurb:
        extra.append("          " + blurb)
    extra.extend("          " + row for row in results)
    extra_html = "\n".join(extra)

    # Rank and band from the last archive Officials Profile, when this person
    # served and is not a current sitting official (those pages redirect).
    archive = last_archive_profile(names)
    history = rank_band_html(archive) if archive else ""

    # Local pages keep the Results heading; primary/general use Research.
    card_heading = heading
    if "local" in cycle:
        card_heading = "Results" if facts else None
    elif heading == "Results":
        card_heading = "Research" if facts else None
    elif not heading and facts:
        card_heading = "Research"

    card = research_card(card_heading, facts, sources)
    script = GENERAL_SCRIPT if "primary" in cycle else ""
    # Preserve a back script id="cand-back" so GENERAL_SCRIPT can rewrite it.
    body = f"""        {back or ""}
        <section class="pf-head" aria-labelledby="h-name">
          <h1 id="h-name">{esc(name)}</h1>
          <p class="pf-sub">{sub}</p>
        </section>
{extra_html}
{history}
{card}"""
    html_class = "cand-local" if "local" in cycle else ""
    title = f"{name} — Profile — WyoVote"
    page.write_text(
        profile_shell(
            name=name,
            title=title,
            description=desc or f"{name}, {year} {kind}.".strip(),
            rel=rel,
            nav_current="candidates",
            html_class=html_class,
            body_inner=body,
            script=script,
        ),
        encoding="utf-8",
    )
    return "profile", archive["slug"] if archive else ""


def rewrite_session_href(href: str) -> str:
    """Point an Officials session href at the Profile when that file exists."""
    if not href or href.startswith(("http://", "https://", "#")):
        return href
    m = re.match(r"^(.*?)(officials/)(?!statewide/)([a-z0-9-]+)\.html(.*)$", href)
    if not m:
        return href
    slug = m.group(3)
    if slug.endswith("-deep"):
        return href
    if (OFFICIALS / f"{slug}-deep.html").is_file():
        return f"{m.group(1)}{m.group(2)}{slug}-deep.html{m.group(4)}"
    return href


def write_redirects(pairs: list[tuple[str, str]]) -> int:
    """pairs: (candidate L3 site-relative path without leading slash, official slug)."""
    existing = REDIRECTS.read_text(encoding="utf-8")
    if REDIR_BEGIN in existing:
        start = existing.find(REDIR_BEGIN)
        end = existing.find(REDIR_END)
        if end == -1:
            raise SystemExit("broken sitting-legislator redirect block")
        end += len(REDIR_END)
        existing = (existing[:start] + existing[end:]).rstrip() + "\n"
    lines = [REDIR_BEGIN, "# Sitting legislators' leftover candidate pages go to their Officials Profile."]
    seen: set[str] = set()
    for rel, slug in sorted(pairs):
        rel = rel.lstrip("/")
        dest = f"/officials/{slug}-deep.html"
        for src in (f"/{rel}", f"/{rel[:-5]}" if rel.endswith(".html") else None):
            if not src or src in seen:
                continue
            seen.add(src)
            lines.append(f"{src} {dest} 301")
    lines.append(REDIR_END)
    REDIRECTS.write_text(existing + "\n" + "\n".join(lines) + "\n", encoding="utf-8")
    return len(seen)


def all_l3_pages() -> list[Path]:
    return sorted(CANDIDATES.glob("*/c/*.html"))


def rewrite_all() -> dict[str, int]:
    counts = {"profile": 0, "pointer": 0, "history": 0, "pages": 0}
    redirects: list[tuple[str, str]] = []
    for path in all_l3_pages():
        kind, extra = rewrite_page(path)
        counts["pages"] += 1
        counts[kind] += 1
        if kind == "pointer" and extra:
            rel = path.relative_to(ROOT).as_posix()
            redirects.append((rel, extra))
        if kind == "profile" and extra:
            counts["history"] += 1
    counts["redirects"] = write_redirects(redirects)
    return counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pages", nargs="*", type=Path)
    parser.add_argument("--all", action="store_true", help="rewrite every candidate L3 page")
    args = parser.parse_args()
    if args.all:
        counts = rewrite_all()
        print(
            "pages {pages}: profile {profile} (rank/band on {history}), "
            "pointer {pointer}, redirects {redirects}".format(**counts)
        )
        return 0
    if not args.pages:
        print("usage: render_candidate_profile.py --all | PAGE.html ...", file=sys.stderr)
        return 2
    for arg in args.pages:
        path = arg if arg.is_absolute() else (Path.cwd() / arg).resolve()
        kind, extra = rewrite_page(path)
        print(kind, extra or "-", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
